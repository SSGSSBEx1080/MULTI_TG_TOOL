def get_ege_stress_deck(count: int = 15, query: str = "") -> dict[str, Any]:
    ql = (query or "").strip().lower()
    if ql:
        filtered = [
            w for w in EGE_STRESS_WORDS
            if ql in w["base"] or ql in w["correct"].lower() or ql in w["pos"].lower() or ql in w["hint"].lower()
        ]
    else:
        pool = list(EGE_STRESS_WORDS)
        # Fisher-Yates cryptographic shuffle
        for i in range(len(pool) - 1, 0, -1):
            j = secrets.randbelow(i + 1)
            pool[i], pool[j] = pool[j], pool[i]
        filtered = pool[: max(1, min(count, len(pool)))]

    quiz = []
    for item in filtered:
        opts = [item["correct"], item["wrong"]]
        if secrets.randbelow(2) == 1:
            opts.reverse()
        quiz.append({**item, "options": opts})

    return {
        "total_corpus": len(EGE_STRESS_WORDS),
        "count": len(quiz),
        "items": quiz,
    }


