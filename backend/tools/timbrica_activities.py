def roll_croco_words(level: str = "all", count: int = 6, letter: str = "") -> dict[str, Any]:
    if level in CROCO_WORDS_DB:
        pool = list(CROCO_WORDS_DB[level])
    else:
        pool = [w for lst in CROCO_WORDS_DB.values() for w in lst]

    let = (letter or "").strip().lower()
    if let:
        pool = [w for w in pool if w.lower().startswith(let)]

    if not pool:
        pool = list(CROCO_WORDS_DB["medium"])

    for i in range(len(pool) - 1, 0, -1):
        j = secrets.randbelow(i + 1)
        pool[i], pool[j] = pool[j], pool[i]

    picked = pool[: max(1, min(count, len(pool)))]
    return {"level": level, "count": len(picked), "words": picked}


