def _preserve_case(orig: str, repl: str) -> str:
    if orig.isupper():
        return repl.upper()
    if orig and orig[0].isupper():
        return repl[0].upper() + repl[1:]
    return repl


def yoficate_russian_text(text: str) -> dict[str, Any]:
    replaced = 0

    def _sub(match: re.Match[str]) -> str:
        nonlocal replaced
        w = match.group(0)
        wl = w.lower()
        if wl in _YO_EXACT_MAP and _YO_EXACT_MAP[wl] != wl:
            replaced += 1
            return _preserve_case(w, _YO_EXACT_MAP[wl])
        return w

    out = re.sub(r"[А-Яа-яЁё]+", _sub, text or "")
    return {"input": text, "output": out, "replacements_count": replaced}


def _apply_translit(text: str, table: dict[str, str], upper_mode: bool = False) -> str:
    buf: list[str] = []
    for ch in text:
        low = ch.lower()
        if low in table:
            mapped = table[low]
            if upper_mode:
                buf.append(mapped.upper())
            elif ch.isupper() and mapped:
                buf.append(mapped[0].upper() + mapped[1:])
            else:
                buf.append(mapped)
        else:
            buf.append(ch.upper() if upper_mode else ch)
    return "".join(buf)


def transliterate_multistandard(text: str) -> dict[str, Any]:
    clean = (text or "").strip()
    icao = _apply_translit(clean, _ICAO_PASSPORT_MAP, upper_mode=True)
    gost = _apply_translit(clean, _GOST_779_B_MAP)
    iso9 = _apply_translit(clean, _ISO9_SCIENTIFIC_MAP)
    slug_raw = _apply_translit(clean.lower(), _ICAO_PASSPORT_MAP)
    slug = re.sub(r"[^a-z0-9]+", "-", slug_raw).strip("-")
    return {
        "original": clean,
        "standards": [
            {"id": "icao_mvd", "title": "Загранпаспорт МВД РФ (ICAO Doc 9303)", "value": icao},
            {"id": "gost_779b", "title": "ГОСТ 7.79-2000 (Система Б)", "value": gost},
            {"id": "iso9", "title": "Научная международная (ISO 9)", "value": iso9},
            {"id": "url_slug", "title": "Веб-адрес (URL Slug)", "value": slug},
        ],
    }


