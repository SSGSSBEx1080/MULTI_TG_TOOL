def roll_random_stand(seed_text: str = "") -> dict[str, Any]:
    if seed_text.strip():
        idx = int(hashlib.sha256(seed_text.strip().lower().encode("utf-8")).hexdigest(), 16) % len(JOJO_STANDS_DB)
    else:
        idx = int(time.time() * 1000) % len(JOJO_STANDS_DB)
    return JOJO_STANDS_DB[idx]


