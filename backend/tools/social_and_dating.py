def get_turing_round(exclude_ids: list[int] | None = None) -> dict[str, Any]:
    excl = set(exclude_ids or [])
    pool = [r for r in TURING_ROUNDS if r["id"] not in excl] or TURING_ROUNDS
    item = random.choice(pool)
    return {
        "id": item["id"],
        "topic": item["topic"],
        "text": item["text"],
        "total_rounds": len(TURING_ROUNDS),
    }


def check_turing_guess(round_id: int, guess: str) -> dict[str, Any]:
    g = (guess or "").strip().lower()
    item = next((r for r in TURING_ROUNDS if r["id"] == int(round_id)), TURING_ROUNDS[0])
    is_correct = g == item["author"]
    return {
        "round_id": item["id"],
        "correct": is_correct,
        "actual_author": item["author"],
        "actual_label": "Живой Человек 🧑" if item["author"] == "human" else "Нейросеть (ИИ) 🤖",
        "clue": item["clue"],
        "xp_reward": 20 if is_correct else 5,
    }


