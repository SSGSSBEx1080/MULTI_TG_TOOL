# 5. LIBRARY OF BABEL SIMULATOR (REVERSIBLE BIJECTIVE HEXAGON ADDRESSING)
# ==============================================================================

BABEL_ALPHABET = " абвгдеёжзийклмнопрстуфхцчшщъыьэюяabcdefghijklmnopqrstuvwxyz0123456789.,!?;:-"
PAGE_LEN = 1280


def _stream_key(hex_id: str, wall: int, shelf: int, vol: int, page: int, length: int = PAGE_LEN) -> list[int]:
    out: list[int] = []
    block_idx = 0
    alpha_n = len(BABEL_ALPHABET)
    while len(out) < length:
        seed = f"BABEL-V6|{hex_id.lower()}|W{wall}|S{shelf}|V{vol}|P{page}|B{block_idx}".encode("utf-8")
        digest = hashlib.sha512(seed).digest()
        for b in digest:
            out.append(b % alpha_n)
            if len(out) >= length:
                break
        block_idx += 1
    return out


def library_of_babel_browse(
    hex_id: str = "borges1941",
    wall: int = 1,
    shelf: int = 1,
    volume: int = 1,
    page: int = 1,
) -> dict[str, Any]:
    w = max(1, min(4, int(wall)))
    s = max(1, min(5, int(shelf)))
    v = max(1, min(32, int(volume)))
    p = max(1, min(410, int(page)))
    hid = (hex_id or "borges1941").strip()[:4096]

    alpha_n = len(BABEL_ALPHABET)
    key = _stream_key(hid[:64], w, s, v, p, PAGE_LEN)

    # If hex_id contains an encoded reversible payload suffix "~<hex>", decode deterministically!
    if "~" in hid:
        prefix, payload_hex = hid.split("~", 1)
        key = _stream_key(prefix[:64], w, s, v, p, PAGE_LEN)
        try:
            offsets = bytes.fromhex(payload_hex)
            chars = []
            for idx in range(PAGE_LEN):
                off = offsets[idx] if idx < len(offsets) else 0
                chars.append(BABEL_ALPHABET[(key[idx] + off) % alpha_n])
            text = "".join(chars)
        except Exception:
            text = "".join(BABEL_ALPHABET[k] for k in key)
    else:
        text = "".join(BABEL_ALPHABET[k] for k in key)

    return {
        "hex_id": hid,
        "wall": w,
        "shelf": s,
        "volume": v,
        "page": p,
        "address": f"Зал #{hid[:16]}{'…' if len(hid) > 16 else ''} • Стена {w} • Полка {s} • Том {v} • Стр. {p}/410",
        "text": text,
        "total_chars": len(text),
    }


def library_of_babel_search(phrase: str, exact_page_only: bool = False) -> dict[str, Any]:
    raw = (phrase or "").strip().lower()
    if not raw:
        raise ValueError("Введите любую фразу, имя или мысль для поиска в Вавилонской библиотеке")
    cleaned = "".join(ch if ch in BABEL_ALPHABET else " " for ch in raw)[:PAGE_LEN]

    h = hashlib.sha256(cleaned.encode("utf-8")).hexdigest()
    prefix = h[:14]
    w = (int(h[14:16], 16) % 4) + 1
    s = (int(h[16:18], 16) % 5) + 1
    v = (int(h[18:20], 16) % 32) + 1
    p = (int(h[20:24], 16) % 410) + 1

    alpha_n = len(BABEL_ALPHABET)
    key = _stream_key(prefix, w, s, v, p, PAGE_LEN)

    if exact_page_only:
        target = cleaned.ljust(PAGE_LEN, " ")
        start_pos = 0
    else:
        pad_left = int(h[24:28], 16) % max(1, PAGE_LEN - len(cleaned))
        noise_chars = [BABEL_ALPHABET[key[i]] for i in range(PAGE_LEN)]
        for idx, ch in enumerate(cleaned):
            noise_chars[pad_left + idx] = ch
        target = "".join(noise_chars)
        start_pos = pad_left

    offsets = bytearray(PAGE_LEN)
    for idx, ch in enumerate(target):
        c_idx = BABEL_ALPHABET.index(ch)
        offsets[idx] = (c_idx - key[idx]) % alpha_n

    full_hex_id = f"{prefix}~{offsets.hex()}"
    page_obj = library_of_babel_browse(full_hex_id, w, s, v, p)
    return {
        **page_obj,
        "matched_phrase": cleaned,
        "match_start": start_pos,
        "match_end": start_pos + len(cleaned),
        "exact_page_only": exact_page_only,
    }


