def _compute_pi_chudnovsky(digits: int) -> str:
    getcontext().prec = digits + 25
    c = 426880 * Decimal(10005).sqrt()
    k = 6
    m = Decimal(1)
    x = Decimal(1)
    l_val = Decimal(13591409)
    s = Decimal(13591409)
    n_terms = max(2, digits // 14 + 2)
    for i in range(1, n_terms):
        m = (m * (k**3 - 16 * k)) / (i**3)
        l_val += 545140134
        x *= -262537412640768000
        s += Decimal(m * l_val) / x
        k += 12
    pi_val = c / s
    return str(pi_val)[: digits + 2]


def _compute_e(digits: int) -> str:
    getcontext().prec = digits + 25
    s = Decimal(2)
    fact = Decimal(1)
    i = 2
    limit = Decimal(10) ** (-(digits + 12))
    while True:
        fact *= i
        term = Decimal(1) / fact
        s += term
        if term < limit:
            break
        i += 1
    return str(s)[: digits + 2]


