def get_earth_stats_and_correlation(
    x_metric: str = "penis_length_cm",
    y_metric: str = "penis_girth_cm",
    sort_by: str = "gdp_ppp_usd",
) -> dict[str, Any]:
    xm = x_metric if x_metric in METRIC_LABELS else "penis_length_cm"
    ym = y_metric if y_metric in METRIC_LABELS else "penis_girth_cm"
    sb = sort_by if sort_by in METRIC_LABELS else xm

    xs = [float(c[xm]) for c in EARTH_STATS_2026_COUNTRIES]
    ys = [float(c[ym]) for c in EARTH_STATS_2026_COUNTRIES]
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    cov = sum((xs[i] - mx) * (ys[i] - my) for i in range(n))
    vx = sum((x - mx) ** 2 for x in xs)
    vy = sum((y - my) ** 2 for y in ys)
    pearson_r = round(cov / math.sqrt(vx * vy), 3) if vx > 0 and vy > 0 else 0.0
    slope = cov / vx if vx > 0 else 0.0
    intercept = my - slope * mx

    ranked = sorted(EARTH_STATS_2026_COUNTRIES, key=lambda c: float(c[sb]), reverse=True)
    return {
        "as_of_date": "25.10.2026",
        "world_population_2026_10_25": 8_312_480_000,
        "metrics": METRIC_LABELS,
        "x_metric": xm,
        "y_metric": ym,
        "x_label": METRIC_LABELS[xm],
        "y_label": METRIC_LABELS[ym],
        "pearson_r": pearson_r,
        "regression": {"slope": round(slope, 5), "intercept": round(intercept, 4)},
        "countries": ranked,
    }
