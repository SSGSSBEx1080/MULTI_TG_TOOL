def get_upcoming_eclipses_and_comets(now_iso: str = "2026-10-25T12:00:00Z") -> dict[str, Any]:
    try:
        ref = datetime.fromisoformat(now_iso.replace("Z", "+00:00"))
    except Exception:
        ref = datetime(2026, 10, 25, 12, 0, tzinfo=timezone.utc)

    enriched = []
    for ev in ASTRONOMICAL_EVENTS:
        dt = datetime.fromisoformat(ev["date_utc"].replace("Z", "+00:00"))
        delta_sec = max(0.0, (dt - ref).total_seconds())
        days = int(delta_sec // 86400)
        hours = int((delta_sec % 86400) // 3600)
        enriched.append(
            {
                **ev,
                "days_left": days,
                "hours_left": hours,
                "countdown_label": f"Через {days} дн. {hours} ч",
            }
        )
    return {"reference_utc": ref.isoformat(), "events": enriched}


